#!/usr/bin/env node
// Maintenance tool (not used by students): rebuild fonts.json from Next's own font list.
//   node build-fonts-json.mjs <path to node_modules/next/dist/compiled/@next/font/dist/google/font-data.json> [next version]
// Run it in an app that has `npm install` done, so the list matches a real Next release.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

// name -> [next/font import name, category]
const WANTED = {
  Inter: ['Inter', 'sans'],
  'DM Sans': ['DM_Sans', 'sans'],
  Manrope: ['Manrope', 'sans'],
  Nunito: ['Nunito', 'sans'],
  'Space Grotesk': ['Space_Grotesk', 'sans'],
  'IBM Plex Sans': ['IBM_Plex_Sans', 'sans'],
  'Source Sans 3': ['Source_Sans_3', 'sans'],
  'Work Sans': ['Work_Sans', 'sans'],
  'Noto Sans': ['Noto_Sans', 'sans'],
  Fraunces: ['Fraunces', 'serif'],
  'Source Serif 4': ['Source_Serif_4', 'serif'],
  Lora: ['Lora', 'serif'],
};

const [dataPath, nextVersion = 'unknown'] = process.argv.slice(2);
if (!dataPath) {
  process.stderr.write('Usage: node build-fonts-json.mjs <font-data.json> [next version]\n');
  process.exit(2);
}
const data = JSON.parse(await readFile(dataPath, 'utf8'));
const fonts = {};
for (const [name, [importName, category]] of Object.entries(WANTED)) {
  const f = data[name];
  if (!f) throw new Error(`${name} is not in Next's font list.`);
  const variable = f.weights.includes('variable');
  const wght = (f.axes ?? []).find((a) => a.tag === 'wght');
  fonts[name] = {
    importName,
    category,
    subsets: [...f.subsets].sort(),
    variable,
    weights: f.weights.filter((w) => w !== 'variable').map(Number).sort((a, b) => a - b),
    ...(variable && wght ? { wght: [wght.min, wght.max] } : {}),
    styles: f.styles,
  };
}
const out = {
  note: 'Generated by build-fonts-json.mjs from the font list that ships inside Next. Do not edit by hand.',
  generatedFrom: `next@${nextVersion} font-data.json`,
  fonts,
};
await writeFile(path.join(here, 'fonts.json'), `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(`Wrote fonts.json with ${Object.keys(fonts).length} fonts.\n`);
