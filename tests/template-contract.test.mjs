import { test } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { readFile, readdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { TEMPLATE } from './verify-helpers.mjs';

// Static checks of the template's v0.3 design contract: marker blocks, variant CSS, shells, home patterns, preview route.
// (The build check across layout and home combinations is run by hand in a scratch copy: it needs npm install.)

const read = (rel) => readFile(path.join(TEMPLATE, ...rel.split('/')), 'utf8');
const SHAPE_VARS = ['--font-size-base', '--h1-size', '--h2-size', '--h3-size', '--heading-weight', '--heading-tracking', '--space', '--pad-card', '--gap', '--content-max'];
const COLOUR_VARS = ['--background', '--foreground', '--card', '--muted', '--line', '--line-strong', '--accent', '--accent-contrast', '--focus', '--danger', '--danger-contrast'];

function block(css, name) {
  const m = new RegExp(`/\\* shipyard:tokens:${name}:start \\*/\\r?\\n([\\s\\S]*?)\\r?\\n\\s*/\\* shipyard:tokens:${name}:end \\*/`).exec(css);
  assert.ok(m, `${name} marker block is missing`);
  return m[1];
}
const varNames = (text) => [...text.matchAll(/^\s*(--[\w-]+)\s*:/gm)].map((m) => m[1]);

test('globals.css: light, shape and dark marker blocks hold exactly the contract variables', async () => {
  const css = await read('src/app/globals.css');
  assert.deepEqual(varNames(block(css, 'light')), [...COLOUR_VARS, '--radius', '--radius-sm', '--shadow']);
  assert.deepEqual(varNames(block(css, 'shape')), SHAPE_VARS);
  assert.deepEqual(varNames(block(css, 'dark')), [...COLOUR_VARS, '--shadow']);
  for (const edge of ['light', 'shape', 'dark']) {
    for (const side of ['start', 'end']) assert.equal(css.split(`/* shipyard:tokens:${edge}:${side} */`).length - 1, 1, `${edge} ${side} marker appears once`);
  }
});

test('globals.css: the shape block sits inside :root, outside the colour markers', async () => {
  const css = await read('src/app/globals.css');
  const root = css.indexOf(':root {');
  const rootEnd = css.indexOf('\n}\n', root);
  const shape = css.indexOf('/* shipyard:tokens:shape:start */');
  assert.ok(root >= 0 && shape > root && shape < rootEnd, 'shape block is inside :root');
  assert.ok(shape > css.indexOf('/* shipyard:tokens:light:end */'), 'shape block comes after the light block');
  assert.ok(css.indexOf('/* shipyard:tokens:dark:start */') > rootEnd, 'dark block is in the dark rule');
});

test('globals.css: every look choice has CSS, matched on any ancestor (not only <html>)', async () => {
  const css = await read('src/app/globals.css');
  const wanted = {
    density: ['compact', 'airy'],
    cards: ['flat', 'elevated', 'tinted'],
    buttons: ['pill', 'outline', 'sharp'],
    header: ['plain', 'centered'],
  };
  for (const [attr, values] of Object.entries(wanted)) {
    for (const v of values) assert.ok(css.includes(`[data-${attr}="${v}"]`), `CSS for data-${attr}="${v}"`);
  }
  // The defaults (regular, bordered, solid, bar) are the plain rules. Attribute selectors must not be pinned to html or :root,
  // so the preview wrapper (a div carrying the data attributes) is styled the same way.
  assert.equal(/(?:^|[\s,{}])(?:html|:root)\[data-/m.test(css), false, 'no html[data-...] or :root[data-...] selectors');
});

test('globals.css: the shared classes and the type and spacing variables are used', async () => {
  const css = await read('src/app/globals.css');
  for (const cls of ['.card', '.btn', '.btn-primary', '.btn-secondary', '.app-header', '.theme-scope', '.tn-in', '.sb-side']) {
    assert.ok(css.includes(`${cls} {`) || css.includes(`${cls},`) || css.includes(`${cls} `), cls);
  }
  assert.match(css, /html\s*\{[^}]*font-size:\s*var\(--font-size-base\)/);
  for (const v of ['--h1-size', '--h2-size', '--h3-size', '--heading-weight', '--heading-tracking', '--pad-card', '--gap', '--space', '--content-max']) {
    const uses = css.split(`var(${v})`).length - 1;
    assert.ok(uses >= 1, `${v} is used`);
  }
});

test('theme.ts has LOOK and HOME_STYLE, layout.tsx puts the look on <html>', async () => {
  const theme = await read('src/lib/theme.ts');
  assert.match(theme, /^\/\/ Generated by Shipyard design\. Edit with \/shipyard:design, not by hand\./);
  assert.match(theme, /export const LOOK = \{ density: "regular", cards: "bordered", buttons: "solid", header: "bar" \} as const;/);
  assert.match(theme, /export const HOME_STYLE: "focus" \| "split" \| "editorial" \| "cards" \| "list" = "focus";/);
  const layout = await read('src/app/layout.tsx');
  for (const attr of ['density', 'cards', 'buttons', 'header']) assert.ok(layout.includes(`data-${attr}={LOOK.${attr}}`), `data-${attr} comes from LOOK`);
  assert.ok(layout.includes('data-layout={LAYOUT}'));
});

test('constants.ts: LAYOUT knows top-nav; AppShell takes a layout override and has a shell for each layout', async () => {
  const constants = await read('src/lib/constants.ts');
  assert.match(constants, /^export const LAYOUT = "<APP_LAYOUT>" as "bottom-nav" \| "sidebar" \| "top-nav";$/m);
  const shell = await read('src/components/AppShell.tsx');
  assert.match(shell, /layout\?: Layout/);
  assert.match(shell, /activeHref\?: string/);
  for (const name of ['SidebarShell', 'TopNavShell', 'BottomNav', 'AppHeader']) assert.ok(shell.includes(`<${name}`), `${name} is used`);
  const topNav = await read('src/components/TopNavShell.tsx');
  assert.match(topNav, /tn-nav/);
  assert.match(topNav, /className="tn-tabbar"/);
});

test('home: five patterns, picked by HOME_STYLE, all words from home-content.ts', async () => {
  const files = await readdir(path.join(TEMPLATE, 'src', 'components', 'home'));
  for (const name of ['HomeFocus', 'HomeSplit', 'HomeEditorial', 'HomeCards', 'HomeList']) {
    assert.ok(files.includes(`${name}.tsx`), name);
    const src = await read(`src/components/home/${name}.tsx`);
    assert.ok(src.includes('@/lib/home-content'), `${name} reads home-content.ts`);
  }
  const index = await read('src/components/home/index.ts');
  for (const key of ['focus', 'split', 'editorial', 'cards', 'list']) assert.ok(new RegExp(`\\b${key}:\\s*Home`).test(index), key);
  const page = await read('src/app/page.tsx');
  assert.ok(page.includes('HOME_PATTERNS[HOME_STYLE]'));
  const content = await read('src/lib/home-content.ts');
  for (const field of ['headline', 'subline', 'ctaPrimary', 'ctaSecondary', 'points', 'entries', 'preview']) assert.ok(new RegExp(`\\b${field}\\b`).test(content), field);
  const points = /points:\s*\[([\s\S]*?)\n\s*\],/.exec(content)?.[1] ?? '';
  assert.equal((points.match(/title:/g) ?? []).length, 3, 'exactly three points');
  assert.ok(content.includes('BRAND'), 'defaults are built from BRAND');
});

test('design preview route: development only, checks the id, reads .shipyard/design, needs no sign-in', async () => {
  const page = await read('src/app/design-preview/[id]/page.tsx');
  assert.match(page, /process\.env\.NODE_ENV === "production"\) notFound\(\)/);
  assert.match(page, /isPreviewId\(id\)/);
  assert.match(page, /"\.shipyard", "design", `\$\{id\}\.preview\.json`/);
  assert.match(page, /dynamic = "force-dynamic"/);
  assert.match(page, /layout=\{/);
  const proxy = await read('src/proxy.ts');
  assert.match(proxy, /matchesPrefix\(pathname, "\/design-preview"\)/);
  assert.match(proxy, /NODE_ENV === "production" \? new NextResponse\(null, \{ status: 404 \}\) : NextResponse\.next\(\)/, 'a production build answers 404, not a sign-in redirect');
  const preview = await read('src/lib/preview.mjs');
  assert.ok(preview.includes('^[a-z0-9-]{1,40}$'));
  const ignored = (await read('.gitignore')).split(/\r?\n/);
  assert.ok(ignored.includes('.shipyard/'));
  assert.ok(ignored.includes('/design-input/'), 'saved screenshots and brand style files must never reach GitHub');
  const chrome = await read('src/components/SiteChrome.tsx');
  assert.ok(chrome.includes('/design-preview'), 'cookie notice and other extras stay out of previews');
});

test('the template passes its own design check', () => {
  const r = spawnSync(process.execPath, [path.join(TEMPLATE, 'scripts', 'design-check.mjs'), '--root', TEMPLATE], { encoding: 'utf8' });
  assert.equal(r.status, 0, `${r.stdout}${r.stderr}`);
});
