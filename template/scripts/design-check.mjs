// Rules

const PALETTE = "slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose";
const UTIL = "bg|text|border|border-[trblxyse]|ring|ring-offset|fill|stroke|from|via|to|divide|outline|decoration|accent|caret|shadow|placeholder|inset-ring|inset-shadow";
const TAILWIND_COLOUR = new RegExp(
  `(?<![\\w-])(?:[a-z0-9-]+:)*(?:${UTIL})-(?:(?:${PALETTE})-(?:50|[1-9]00|950)|white|black)(?:\\/\\d+|\\/\\[[^\\]]+\\])?(?![\\w-])`,
);
const HEX = /(?<![&\w])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3,4})(?![\w-])/g;
const ANCHOR_BEFORE = /(?:href|to|id|htmlFor|aria-controls|aria-labelledby|aria-describedby)\s*=\s*\{?\s*["'`]$/;
const COLOUR_FN = /(?<![\w-])(?:rgba?|hsla?|hwb|oklch|oklab)\(\s*(?!var\()/;
const GRADIENT = /(?:linear|radial|conic)-gradient\(|(?<![\w-])bg-(?:gradient|linear|radial|conic)(?:-|\/|\b)(?!none)|(?<![\w-])from-[^\s"'`]+[^\n]*?(?<![\w-])to-[^\s"'`]+/;
const EM_DASH = /—/;
// Symbols that are typography, not pictures: (c) (r) tm, arrows, info.
const EMOJI = /(?![©®™ℹ↔-↙↩↪✓✗])\p{Extended_Pictographic}/u;
const PLACEHOLDER = [/lorem ipsum/i, /your tagline here/i, /\bFeature [1-9]\b/, /\bTODO\b/, /\bplaceholder text\b/i];
const FAKE_PROOF = [
  /\b\d[\d,.]*\s?[kKmM]?\+\s*(?:happy |active |satisfied )?(?:users|customers|people|members|downloads|teams|companies|clients|reviews)\b/i,
  /[★⭐]{3,}/u,
  /\btrusted by\b/i,
  /#1[- ](?:rated|app|choice|ranked)/i,
  /\bas seen on\b/i,
  /\bjoin (?:thousands|millions|hundreds)\b/i,
  /\b\d[\d,.]*\+? (?:five|5)[- ]star\b/i,
];
const AI_BADGE = [/powered by AI/i, /AI[- ]powered/i, /✨/u, /made with AI/i];
const NATIVE_ALERT = /(?<![\w$.])(?:(?:window|globalThis|self)\.)?(?:alert|confirm|prompt)\(/;

function lineStarts(text) {
  const starts = [0];
  for (let i = 0; i < text.length; i++) if (text[i] === "\n") starts.push(i + 1);
  return starts;
}
function lineOf(starts, offset) {
  let lo = 0;
  let hi = starts.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (starts[mid] <= offset) lo = mid;
    else hi = mid - 1;
  }
  return lo + 1;
}

/** Find a regex (or list of regexes) in text and return each match's offset. */
function* matches(text, res) {
  for (const re of Array.isArray(res) ? res : [res]) {
    const g = new RegExp(re.source, re.flags.includes("g") ? re.flags : `${re.flags}g`);
    for (const m of text.matchAll(g)) yield { index: m.index, text: m[0] };
  }
}

/** px/rem/em/% font-size values below 16px. Returns true if too small, false if fine or unknown. */
export function isSmallFontSize(value) {
  const v = value.trim().toLowerCase().replace(/\s*!important$/, "");
  if (/^(?:x-small|xx-small|xxx-small|small|smaller)$/.test(v)) return true;
  const m = /^(\d*\.?\d+)(px|rem|em|%|pt)$/.exec(v);
  if (!m) return false; // inherit, var(), clamp(), calc(): can not tell
  const num = Number(m[1]);
  if (m[2] === "px") return num < 16;
  if (m[2] === "rem" || m[2] === "em") return num < 1;
  if (m[2] === "%") return num < 100;
  return num < 12; // pt
}

const INPUT_SELECTOR = /(?:^|[\s,>+~(])(?:input|textarea|select)(?![\w-])|\.(?:input|textarea|select)(?![\w-])/;

/** CSS: find rules aimed at inputs that set a font-size under 16px. Returns offsets into `css`. */
function smallInputRules(css) {
  const found = [];
  const re = /([^{}]+)\{([^{}]*)\}/g;
  for (const m of css.matchAll(re)) {
    const selector = m[1].replace(/\/\*[\s\S]*?\*\//g, " ").trim();
    if (!INPUT_SELECTOR.test(selector)) continue;
    const body = m[2];
    const fs = /(?:^|;|\s)font-size\s*:\s*([^;}]+)/.exec(body);
    if (fs && isSmallFontSize(fs[1])) {
      const bodyStart = m.index + m[0].indexOf("{") + 1;
      found.push(bodyStart + fs.index + fs[0].indexOf("font-size"));
    }
  }
  return found;
}

/** TSX: <input className="... text-sm"> and friends. Returns offsets. */
function smallInputTags(code) {
  const found = [];
  const re = /<(?:input|textarea|select)(?=[\s/>])[^>]*>/g;
  for (const m of code.matchAll(re)) {
    const tag = m[0];
    const attrs = tag.replace(/^<\w+/, "");
    if (/(?<![\w-])input(?![\w-])/.test(attrs)) continue; // the .input class sets 16px itself
    if (/type\s*=\s*\{?["'](?:checkbox|radio|range|file|hidden|submit|button|reset|image|color)["']/.test(attrs)) continue;
    const small = /(?<![\w-])(?:[a-z0-9-]+:)*text-(?:xs|sm|\[(\d*\.?\d+)(px|rem)\])(?![\w-])/.exec(attrs);
    if (!small) continue;
    if (small[1] !== undefined && !isSmallFontSize(`${small[1]}${small[2]}`)) continue;
    found.push(m.index + tag.indexOf(small[0]));
  }
  return found;
}

/**
 * Check one file. `file` is the path relative to the app folder with forward slashes (src/app/page.tsx).
 * Returns [{ file, line, rule, hint }].
 */
export function checkSource(file, text) {
  const ext = path.extname(file).toLowerCase();
  if (!EXTENSIONS.has(ext) || SKIPPED_FILES.has(file)) return [];
  const isCss = ext === ".css";
  const isTs = ext === ".ts" || ext === ".tsx";
  const isJsx = ext === ".tsx";
  const raw = text.replace(/\r\n/g, "\n");
  const rawLines = raw.split("\n");
  const starts = lineStarts(raw);

  let code;
  let bare;
  let ui = "";
  if (isCss) {
    code = raw.replace(/\/\*[\s\S]*?\*\//g, (c) => c.replace(/[^\n]/g, " "));
    bare = code;
  } else {
    const lexed = lexScript(raw);
    code = lexed.code;
    bare = lexed.bare;
    if (isTs) ui = uiText(lexed, isJsx);
  }

  // Allow comments live in the raw text (they are comments, so the cleaned text has lost them).
  const fileAllows = new Set();
  for (const m of raw.matchAll(/design-check:\s*allow-file\s+([a-z-]+)/g)) fileAllows.add(m[1]);
  const allowed = (rule, line) => {
    const names = [rule, ...(ALIASES[rule] ?? [])];
    if (names.some((n) => fileAllows.has(n))) return true;
    const near = `${rawLines[line - 2] ?? ""}\n${rawLines[line - 1] ?? ""}`;
    return names.some((n) => new RegExp(`design-check:\\s*allow-${n}(?![\\w-])`).test(near)) || (rule === "fake-proof" && /design-check:\s*real-data/.test(near));
  };

  const findings = [];
  const seen = new Set();
  const add = (rule, offset) => {
    const line = lineOf(starts, offset);
    if (allowed(rule, line)) return;
    const key = `${rule}:${line}`;
    if (seen.has(key)) return;
    seen.add(key);
    findings.push({ file, line, rule, hint: HINTS[rule] });
  };

  // 1. colours
  if (!COLOUR_FILES.some((re) => re.test(file))) {
    for (const m of matches(code, HEX)) {
      if (ANCHOR_BEFORE.test(code.slice(Math.max(0, m.index - 24), m.index))) continue;
      add("hard-coded-colour", m.index);
    }
    for (const m of matches(code, [COLOUR_FN, TAILWIND_COLOUR])) add("hard-coded-colour", m.index);
  }
  // 2. gradients
  for (const m of matches(code, GRADIENT)) add("gradient", m.index);

  // 9. small text in inputs
  if (isCss) for (const offset of smallInputRules(code)) add("small-input-text", offset);
  if (isJsx) for (const offset of smallInputTags(code)) add("small-input-text", offset);

  if (isTs) {
    // 3, 4. characters
    for (const m of matches(code, EM_DASH)) add("em-dash", m.index);
    const noSparkle = code.replace(/✨/gu, " ");
    for (const m of matches(noSparkle, EMOJI)) add("emoji-in-ui", m.index);
    // 5, 6, 7, 10. words a visitor can read
    for (const m of matches(ui, PLACEHOLDER)) add("placeholder-text", m.index);
    for (const m of matches(ui, FAKE_PROOF)) add("fake-proof", m.index);
    for (const m of matches(ui, AI_BADGE)) add("ai-badge", m.index);
    // Text that STARTS with "Tip:" (a run of text begins at a line start or after a gap left by a tag).
    let lineOffset = 0;
    for (const line of ui.split("\n")) {
      const m = /(?:^|\s{2,})((?:pro[ -])?tip:)/i.exec(line);
      if (m) add("tip-box", lineOffset + m.index + m[0].length - m[1].length);
      lineOffset += line.length + 1;
    }
    // 8. native pop-ups (code only: not in strings or comments)
    for (const m of matches(bare, NATIVE_ALERT)) add("native-alert", m.index);
  }

  return findings.sort((a, b) => a.line - b.line || a.rule.localeCompare(b.rule));
}

// ---------------------------------------------------------------------------------------------
// Running over a folder

function walk(dir, rel, out) {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    if (e.name === "node_modules" || e.name.startsWith(".")) continue;
    const full = path.join(dir, e.name);
    const r = `${rel}/${e.name}`;
    if (e.isDirectory()) walk(full, r, out);
    else if (e.isFile() && EXTENSIONS.has(path.extname(e.name).toLowerCase())) out.push({ full, rel: r });
  }
}

/** Check every source file under <root>/src. Returns { files, findings }. */
export function checkApp(root) {
  const src = path.join(root, "src");
  let isDir = false;
  try {
    isDir = statSync(src).isDirectory();
  } catch {
    isDir = false;
  }
  if (!isDir) throw new Error("no src folder");
  const list = [];
  walk(src, "src", list);
  list.sort((a, b) => a.rel.localeCompare(b.rel));
  const findings = [];
  let files = 0;
  for (const f of list) {
    if (SKIPPED_FILES.has(f.rel)) continue;
    let text;
    try {
      text = readFileSync(f.full, "utf8");
    } catch {
      continue;
    }
    files++;
    findings.push(...checkSource(f.rel, text));
  }
  return { files, findings };
}

const HELP = `Usage: node scripts/design-check.mjs [--json] [--root <app folder>] [--help]

Looks in src/ for the signs of a generic, machine-made look and fails if it finds any:
${RULES.map((r) => `  ${r.padEnd(18)} ${HINTS[r]}`).join("\n")}
A line that is fine on purpose can say so in a comment: design-check: allow-<rule name>
Exit code: 0 clean, 1 found something, 2 could not run.`;

function main(argv) {
  let root = null;
  const rest = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--root") root = argv[++i] ?? "";
    else if (argv[i].startsWith("--root=")) root = argv[i].slice(7);
    else rest.push(argv[i]);
  }
  if (rest.includes("--help") || rest.includes("-h")) {
    console.log(HELP);
    return 0;
  }
  const unknown = rest.filter((a) => a !== "--json");
  if (unknown.length > 0 || root === "") {
    console.error(`${unknown.length > 0 ? `Unknown option: ${unknown[0]}` : "--root needs a folder"}\n\n${HELP}`);
    return 2;
  }
  const json = rest.includes("--json");
  const appRoot = path.resolve(root ?? path.join(path.dirname(fileURLToPath(import.meta.url)), ".."));

  let result;
  try {
    result = checkApp(appRoot);
  } catch {
    const message = "Could not find the src folder. Run this inside the app folder.";
    if (json) console.log(JSON.stringify({ ok: false, error: message }));
    else console.error(`✗ ${message}`);
    return 2;
  }
  const { files, findings } = result;
  if (json) {
    console.log(JSON.stringify({ ok: findings.length === 0, scanned: files, findings }, null, 2));
  } else if (findings.length === 0) {
    console.log(`✓ Design check passed (${files} files)`);
  } else {
    console.error(`✗ ${findings.length} design problem${findings.length === 1 ? "" : "s"} found:`);
    for (const f of findings) console.error(`  ${f.file}:${f.line} ${f.rule} — ${f.hint}`);
  }
  return findings.length === 0 ? 0 : 1;
}

// Compare real paths: Node resolves symlinks in import.meta.url but not in argv[1], so a plain
// string comparison silently does nothing when the app is reached through a symlinked folder
// (/tmp on macOS). A check that prints nothing and exits 0 looks like a pass.
function startedAsCheck() {
  if (!process.argv[1]) return false;
  try {
    if (realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) return true;
  } catch {
    // fall through to the name check
  }
  return path.basename(process.argv[1]) === "design-check.mjs";
}

if (startedAsCheck()) {
  process.exitCode = main(process.argv.slice(2));
}
