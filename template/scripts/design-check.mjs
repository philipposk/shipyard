#!/usr/bin/env node
// Looks for the usual signs of a generic, "made by AI" interface in src/ and fails if it finds any:
// hard-coded colours, gradients, em dashes, emoji, placeholder text, fake numbers, native pop-ups and so on.
// Standalone (Node built-ins only). Runs with `npm run check:design`, in CI, and from Shipyard `verify`.
// It prints file:line, the rule and how to fix it.
//
//   node scripts/design-check.mjs            check src/ of this app
//   node scripts/design-check.mjs --json     machine-readable output
//   node scripts/design-check.mjs --root <dir>   check another app folder (used by tests)
//
// A line that is fine on purpose can say so in a comment on the same line or the line before:
//   design-check: allow-gradient     design-check: allow-colour     design-check: real-data
//   design-check: allow-<rule name> works for every rule. `design-check: allow-file <rule name>` covers the whole file.
//
// Exit code: 0 clean, 1 found something, 2 could not run.

import { readdirSync, readFileSync, realpathSync, statSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const RULES = [
  "hard-coded-colour",
  "gradient",
  "em-dash",
  "emoji-in-ui",
  "placeholder-text",
  "fake-proof",
  "ai-badge",
  "native-alert",
  "small-input-text",
  "tip-box",
];

/** Words in an allow comment that stand for a rule: `allow-colour` is the same as `allow-hard-coded-colour`. */
const ALIASES = {
  "hard-coded-colour": ["colour", "color", "hard-coded-color"],
  "emoji-in-ui": ["emoji"],
  "small-input-text": ["small-input"],
  "native-alert": ["alert"],
  "fake-proof": ["real-data"],
};

const HINTS = {
  "hard-coded-colour": "use a token like var(--accent) or var(--muted); add a new variable in globals.css if none fits",
  gradient: "use a flat colour from the tokens (skeleton loaders may say: design-check: allow-gradient)",
  "em-dash": "use a comma, colon or full stop",
  "emoji-in-ui": "use an icon from the app, or no symbol at all",
  "placeholder-text": "write the real text for this screen",
  "fake-proof": "show only real numbers and real reviews (real data may say: design-check: real-data)",
  "ai-badge": "remove it; people care what the app does, not what it runs on",
  "native-alert": "use the ConfirmModal component or an inline message",
  "small-input-text": "inputs need font-size 16px or more, or iPhones zoom in when you tap them",
  "tip-box": "put the help in the screen itself instead of a Tip box",
};

/** Files that hold colours on purpose. Everything else must use tokens. */
const COLOUR_FILES = [/^src\/app\/globals\.css$/, /^src\/app\/(?:.*\/)?opengraph-image[^/]*$/];
/** Generated by the design step: not checked. */
const SKIPPED_FILES = new Set(["src/lib/theme.ts", "src/lib/fonts.ts"]);
const EXTENSIONS = new Set([".ts", ".tsx", ".css", ".mjs"]);

// ---------------------------------------------------------------------------------------------
// Reading code without being fooled by comments and strings

/**
 * Walk TypeScript/JavaScript text once and return three strings of the SAME length (newlines kept,
 * so offsets map to line numbers):
 *   code    comments blanked, everything else kept
 *   bare    comments and the inside of strings blanked (what is left is code and JSX text)
 *   strings the inside of strings and template literals only (the rest blanked)
 * Good enough for rules; not a full parser. A quote inside JSX text ("Don't") ends at the line end.
 */
export function lexScript(src) {
  const n = src.length;
  const code = src.split("");
  const bare = src.split("");
  const strs = new Array(n).fill(" ");
  for (let i = 0; i < n; i++) if (src[i] === "\n") strs[i] = "\n";
  const blank = (arr, from, to) => {
    for (let k = from; k < to; k++) if (arr[k] !== "\n" && arr[k] !== "\r") arr[k] = " ";
  };
  const keep = (from, to) => {
    for (let k = from; k < to; k++) if (src[k] !== "\n" && src[k] !== "\r") strs[k] = src[k];
  };

  // frames: { kind: "code" | "template", braces }
  const stack = [{ kind: "code", braces: 0 }];
  let prevSig = ""; // last non-space character seen in code
  let prevWord = "";
  let i = 0;
  while (i < n) {
    const frame = stack[stack.length - 1];
    const c = src[i];
    const d = src[i + 1];

    if (frame.kind === "template") {
      const start = i;
      while (i < n) {
        if (src[i] === "\\") i += 2;
        else if (src[i] === "`") break;
        else if (src[i] === "$" && src[i + 1] === "{") break;
        else i++;
      }
      i = Math.min(i, n);
      keep(start, i);
      blank(bare, start, i);
      if (src[i] === "`") {
        stack.pop();
        prevSig = "`";
        i++;
      } else if (src[i] === "$") {
        stack.push({ kind: "code", braces: 0 });
        prevSig = "{";
        i += 2;
      }
      continue;
    }

    // code
    if (c === "/" && d === "/") {
      const start = i;
      while (i < n && src[i] !== "\n") i++;
      blank(code, start, i);
      blank(bare, start, i);
      continue;
    }
    if (c === "/" && d === "*") {
      const start = i;
      const end = src.indexOf("*/", i + 2);
      i = end === -1 ? n : end + 2;
      blank(code, start, i);
      blank(bare, start, i);
      continue;
    }
    if (c === '"' || c === "'") {
      const start = i;
      i++;
      while (i < n && src[i] !== c && src[i] !== "\n") i += src[i] === "\\" ? 2 : 1;
      const end = Math.min(i, n);
      keep(start + 1, end);
      blank(bare, start + 1, end);
      if (src[end] === c) i = end + 1;
      else i = end; // unterminated (an apostrophe in JSX text): stop at the line end
      prevSig = c;
      continue;
    }
    if (c === "`") {
      stack.push({ kind: "template", braces: 0 });
      prevSig = "`";
      i++;
      continue;
    }
    if (c === "/" && (prevSig === "" || "(,=:[!&|?{};".includes(prevSig) || prevWord === "return")) {
      // Possibly a regular expression literal. Only treat it as one if it closes on this line.
      let j = i + 1;
      let inClass = false;
      while (j < n && src[j] !== "\n") {
        if (src[j] === "\\") j += 2;
        else if (src[j] === "[") { inClass = true; j++; }
        else if (src[j] === "]") { inClass = false; j++; }
        else if (src[j] === "/" && !inClass) break;
        else j++;
      }
      if (j < n && src[j] === "/") {
        blank(bare, i + 1, j);
        i = j + 1;
        prevSig = "/";
        continue;
      }
    }
    if (c === "{") frame.braces++;
    if (c === "}") {
      if (frame.braces === 0 && stack.length > 1) {
        stack.pop();
        i++;
        continue;
      }
      frame.braces--;
    }
    if (/\s/.test(c)) {
      i++;
      continue;
    }
    if (/[A-Za-z_$]/.test(c)) {
      let j = i;
      while (j < n && /[\w$]/.test(src[j])) j++;
      prevWord = src.slice(i, j);
      prevSig = src[j - 1];
      i = j;
      continue;
    }
    prevWord = "";
    prevSig = c;
    i++;
  }
  return { code: code.join(""), bare: bare.join(""), strings: strs.join("") };
}

/** Text a visitor can read: string literals plus the text between JSX tags. Same length as the input. */
export function uiText(lexed, isJsx) {
  const out = lexed.strings.split("");
  if (isJsx) {
    const re = /(?:(?<!=)>|\})([^<>{}]+)(?=<|\{|$)/g;
    for (const m of lexed.bare.matchAll(re)) {
      const start = m.index + m[0].length - m[1].length;
      for (let k = 0; k < m[1].length; k++) if (m[1][k] !== "\n") out[start + k] = m[1][k];
    }
    // Lines that are nothing but text (no code characters) are JSX text too.
    let offset = 0;
    for (const line of lexed.bare.split("\n")) {
      if (line.trim() && !/[<>{}=;()[\]]/.test(line)) {
        for (let k = 0; k < line.length; k++) out[offset + k] = line[k];
      }
      offset += line.length + 1;
    }
  }
  return out.join("");
}

